"""Generate src/core/data/unicode-scripts.ts: the Unicode Script property as libraqm 0.10.5 (matplotlib 3.11's text layout)
sees it through HarfBuzz 14.1's built-in UCD tables (Unicode 17.0.0), for _raqm_resolve_scripts' run itemization.

raqm reads hb_unicode_script(), except that a nonspacing mark (General_Category Mn) counts as Inherited whatever its own
script. mpl only needs to tell apart the scripts its baked faces carry (Common, Inherited, Latin, Greek): every other script
is one bucket, Other. Characters of an Other script draw as .notdef in every baked face, and .notdef neither kerns nor takes
part in GSUB, so merging two adjacent Other scripts into one run lays out what raqm lays out.

Run: python3 scripts/gen_unicode_scripts.py   (downloads the two pinned UCD files; no matplotlib needed)
"""
import hashlib, os, urllib.request

UCD = "https://www.unicode.org/Public/17.0.0/ucd/"
FILES = {
    "Scripts.txt": "9f5e50d3abaee7d6ce09480f325c706f485ae3240912527e651954d2d6b035bf",
    "extracted/DerivedGeneralCategory.txt": "d62e5bab70ca74f099343f71224fa051cb1fdd61a1ab45c0488c44cfc0b6102e",
}
OUT = os.path.join(os.path.dirname(__file__), "..", "src", "core", "data", "unicode-scripts.ts")
BUCKETS = ["Common", "Inherited", "Latin", "Greek", "Other"]


def fetch(name):
    body = urllib.request.urlopen(UCD + name).read()
    got = hashlib.sha256(body).hexdigest()
    if got != FILES[name]:
        raise SystemExit(f"{name}: sha256 {got} != {FILES[name]}")
    return body.decode("utf-8")


def entries(text):
    for line in text.splitlines():
        line = line.split("#")[0].strip()
        if not line:
            continue
        r, value = [x.strip() for x in line.split(";")]
        a, _, b = r.partition("..")
        yield int(a, 16), int(b or a, 16), value


script = ["Unknown"] * 0x110000
for a, b, v in entries(fetch("Scripts.txt")):
    for c in range(a, b + 1):
        script[c] = v
mn = [False] * 0x110000
for a, b, v in entries(fetch("extracted/DerivedGeneralCategory.txt")):
    if v == "Mn":
        for c in range(a, b + 1):
            mn[c] = True


def bucket(c):
    if mn[c]:
        # _raqm_unicode_script: combining marks inherit the script of their bases. A mark of an Other script stays Other:
        # it only ever follows that script's (.notdef) letters, where the two readings give the same runs.
        return "Other" if script[c] not in ("Common", "Inherited", "Latin", "Greek") else "Inherited"
    s = script[c]
    return s if s in ("Common", "Inherited", "Latin", "Greek") else "Other"


starts, kinds, prev = [], [], None
for c in range(0x110000):
    k = bucket(c)
    if k != prev:
        starts.append(c)
        kinds.append(BUCKETS.index(k))
        prev = k
# packed: each range as hex (start − previous start) followed by its bucket digit, comma separated
packed = ",".join(f"{format(s - (starts[i - 1] if i else 0), 'x')}{k}" for i, (s, k) in enumerate(zip(starts, kinds)))
with open(OUT, "w") as f:
    f.write("// Generated by scripts/gen_unicode_scripts.py from the Unicode 17.0.0 UCD (HarfBuzz 14.1's). Do not edit.\n"
            "// Script ranges: each entry is the hex distance from the previous range's first code point, then its bucket\n"
            f"// (an index into SCRIPT_BUCKETS). {len(starts)} ranges.\n"
            f"export const SCRIPT_BUCKETS = {BUCKETS!r} as const;\n"
            f"export const SCRIPT_RANGES = '{packed}';\n")
print(f"{len(starts)} ranges, {len(packed)} chars")
